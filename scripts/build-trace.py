"""Turn a raw `claude -p --output-format stream-json` recording into the page's trace JSON.

Usage: python scripts/build-trace.py <raw.jsonl> data/<name>.json <recording-dir>
(also writes site/data/<name>.js)

Redacts the recording folder and the local user name. Everything else is kept as recorded.
Token counts come from the API usage on each model call: the context a call reads is
input + cache_read + cache_creation; the growth between two calls is what the previous
step added (the model's request plus the tool results).
"""
import getpass
import json
import pathlib
import re
import sys

raw_path, out_path, rec_dir = sys.argv[1], sys.argv[2], sys.argv[3]
rec_variants = {rec_dir, rec_dir.replace("\\", "/"), rec_dir.replace("/", "\\")}
rec_variants |= {v.replace("\\\\", "\\") for v in list(rec_variants)}


def redact(s):
    for v in sorted(rec_variants, key=len, reverse=True):
        s = s.replace(v, "~/cart")
    s = s.replace("~/cart\\", "~/cart/")
    s = re.sub(rf"\b{re.escape(getpass.getuser())}\b", "you", s)
    return s


def clean(obj):
    if isinstance(obj, str):
        return redact(obj)
    if isinstance(obj, list):
        return [clean(x) for x in obj]
    if isinstance(obj, dict):
        return {k: clean(v) for k, v in obj.items()}
    return obj


events = [json.loads(l) for l in open(raw_path, encoding="utf-8")]
init = next(e for e in events if e.get("type") == "system" and e.get("subtype") == "init")
result = next(e for e in events if e.get("type") == "result")

calls = []  # one per model call (assistant message id)
by_id = {}
pending = {}  # tool_use_id -> step
for e in events:
    if e.get("type") == "assistant":
        m = e["message"]
        if m["id"] not in by_id:
            u = m["usage"]
            call = {
                "context_tokens": u["input_tokens"] + u["cache_read_input_tokens"] + u["cache_creation_input_tokens"],
                "cached_tokens": u["cache_read_input_tokens"],
                "new_tokens": u["input_tokens"] + u["cache_creation_input_tokens"],
                "output": [],
            }
            by_id[m["id"]] = call
            calls.append(call)
        call = by_id[m["id"]]
        for c in m["content"]:
            if c["type"] == "text":
                call["output"].append({"kind": "text", "text": c["text"]})
            elif c["type"] == "tool_use":
                step = {"kind": "tool", "id": c["id"], "tool": c["name"], "input": c["input"], "result": None}
                call["output"].append(step)
                pending[c["id"]] = step
    elif e.get("type") == "user":
        for c in e["message"]["content"]:
            if c.get("type") == "tool_result":
                cc = c["content"]
                text = cc if isinstance(cc, str) else "\n".join(x.get("text", "") for x in cc)
                pending[c["tool_use_id"]]["result"] = {"text": text.replace("\r\n", "\n"), "is_error": bool(c.get("is_error"))}

for i, call in enumerate(calls):
    call["added_since_previous"] = None if i == 0 else call["context_tokens"] - calls[i - 1]["context_tokens"]

trace = {
    "source": "Real Claude Code session, recorded with claude -p --output-format stream-json. "
              "Paths and the local user name are redacted; nothing else is edited.",
    "recorded": "2026-11-08",
    "model": init["model"],
    "claude_code_version": init["claude_code_version"],
    "prompt": "The tests are failing. Please find the bug and fix it.",
    "tools_available": init["tools"],
    "calls": calls,
    "totals": {
        "model_calls": len(calls),
        "output_tokens": result["usage"]["output_tokens"],
        "cache_read_tokens": result["usage"]["cache_read_input_tokens"],
        "cache_write_tokens": result["usage"]["cache_creation_input_tokens"],
        "cost_usd": round(result["total_cost_usd"], 4),
        "duration_s": round(result["duration_ms"] / 1000, 1),
    },
    "final_answer": result["result"],
}
trace = clean(trace)
json.dump(trace, open(out_path, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
# The page loads the trace as a script so it also works when opened straight from disk.
out = pathlib.Path(out_path)
js_path = out.parent.parent / "site" / "data" / (out.stem + ".js")
js_path.parent.mkdir(parents=True, exist_ok=True)
with open(js_path, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build-trace.py. Do not edit.\n")
    f.write("window.TRACE = " + json.dumps(trace, ensure_ascii=False) + ";\n")
print("calls", len(calls), [c["context_tokens"] for c in calls])
